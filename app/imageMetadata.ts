function normalizeImageSrc(src: string) {
  try {
    return decodeURI(src);
  } catch {
    return src;
  }
}

export function getImageDimensions(src: string): ImageDimensions {
  return imageDimensions.get(normalizeImageSrc(src)) ?? fallbackImageDimensions;
}
